CREATE EXTENSION IF NOT EXISTS timescaledb;

CREATE TABLE IF NOT EXISTS sensor_data (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY,
    device_id   TEXT             NOT NULL,
    sensor_id   TEXT,
    temperature DOUBLE PRECISION NOT NULL,
    humidity    DOUBLE PRECISION NOT NULL,
    sensors     JSONB            NOT NULL DEFAULT '{}'::jsonb,
    meta        JSONB            NOT NULL DEFAULT '{}'::jsonb,
    created_at  TIMESTAMPTZ      NOT NULL DEFAULT now(),
    PRIMARY KEY (id, created_at)
);

SELECT create_hypertable(
    'sensor_data', 'created_at',
    chunk_time_interval => INTERVAL '7 days',
    if_not_exists => true
);

CREATE INDEX IF NOT EXISTS idx_sensor_data_device_time ON sensor_data (device_id, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_sensor_data_sensor_id ON sensor_data (sensor_id);
CREATE UNIQUE INDEX IF NOT EXISTS idx_sensor_data_event_unique ON sensor_data (device_id, created_at, sensors);
