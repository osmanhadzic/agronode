package repositories

import (
	"context"
	"crypto/sha256"
	"encoding/hex"
	"fmt"
	"regexp"
	"sort"
	"strings"
	"sync"
	"time"

	"gorm.io/gorm"
)

const (
	sensorSeriesTablePrefix = "ts_"
	maxSensorSlugLength     = 40
	sensorSeriesDDLLockKey  = 7301001
)

var unsafeIdentifierChars = regexp.MustCompile(`[^a-z0-9_]`)

// SensorSeriesStore writes every sensor value into its own TimescaleDB
// hypertable, creating the table the first time a sensor is seen.
type SensorSeriesStore struct {
	timeseries *gorm.DB
	known      sync.Map
}

func NewSensorSeriesStore(timeseries *gorm.DB) *SensorSeriesStore {
	return &SensorSeriesStore{timeseries: timeseries}
}

// SensorSeriesTableName maps a sensor id to a safe, unique table name.
// Ids that are not already valid identifiers get a hash suffix so that
// different ids (e.g. "dht11-temp" and "dht11_temp") never share a table.
func SensorSeriesTableName(sensorID string) string {
	trimmed := strings.TrimSpace(sensorID)
	slug := unsafeIdentifierChars.ReplaceAllString(strings.ToLower(trimmed), "_")
	if len(slug) > maxSensorSlugLength {
		slug = slug[:maxSensorSlugLength]
	}

	if slug == trimmed && trimmed != "" {
		return sensorSeriesTablePrefix + slug
	}

	sum := sha256.Sum256([]byte(trimmed))
	return sensorSeriesTablePrefix + slug + "_" + hex.EncodeToString(sum[:4])
}

func (store *SensorSeriesStore) Insert(ctx context.Context, sensorID, deviceID string, value float64, createdAt time.Time) error {
	if strings.TrimSpace(sensorID) == "" {
		return nil
	}

	table := SensorSeriesTableName(sensorID)
	if err := store.ensureTable(ctx, table, sensorID); err != nil {
		return err
	}

	return store.timeseries.WithContext(ctx).Exec(
		fmt.Sprintf(`INSERT INTO %q (time, device_id, value) VALUES (?, ?, ?) ON CONFLICT (device_id, time) DO NOTHING`, table),
		createdAt, deviceID, value,
	).Error
}

func (store *SensorSeriesStore) isPostgres() bool {
	return store.timeseries.Dialector.Name() == "postgres"
}

func (store *SensorSeriesStore) ensureTable(ctx context.Context, table, sensorID string) error {
	if _, ok := store.known.Load(table); ok {
		return nil
	}

	timeType := "DATETIME"
	if store.isPostgres() {
		timeType = "TIMESTAMPTZ"
	}

	err := store.timeseries.WithContext(ctx).Transaction(func(tx *gorm.DB) error {
		if store.isPostgres() {
			// Serialise DDL so concurrent first readings of a sensor do not race.
			if err := tx.Exec("SELECT pg_advisory_xact_lock(?)", sensorSeriesDDLLockKey).Error; err != nil {
				return err
			}
		}

		// table is generated by SensorSeriesTableName and contains only [a-z0-9_].
		statements := []string{
			fmt.Sprintf(`CREATE TABLE IF NOT EXISTS %q (
				time      %s NOT NULL,
				device_id TEXT NOT NULL,
				value     DOUBLE PRECISION NOT NULL
			)`, table, timeType),
		}
		if store.isPostgres() {
			statements = append(statements,
				fmt.Sprintf(`SELECT create_hypertable('%s', 'time', chunk_time_interval => INTERVAL '7 days', if_not_exists => true)`, table))
		}
		statements = append(statements,
			fmt.Sprintf(`CREATE UNIQUE INDEX IF NOT EXISTS %q ON %q (device_id, time DESC)`, table+"_device_time_idx", table))
		for _, statement := range statements {
			if err := tx.Exec(statement).Error; err != nil {
				return err
			}
		}

		return tx.Exec(
			`INSERT INTO sensor_series_tables (sensor_id, table_name) VALUES (?, ?) ON CONFLICT (sensor_id) DO NOTHING`,
			sensorID, table,
		).Error
	})
	if err != nil {
		return fmt.Errorf("ensure sensor table %s: %w", table, err)
	}

	store.known.Store(table, struct{}{})
	return nil
}

// SeriesPoint is a single stored sensor value.
type SeriesPoint struct {
	SensorID string
	DeviceID string
	Value    float64
	Time     time.Time
}

// SeriesQuery filters points; empty DeviceIDs means every device.
type SeriesQuery struct {
	DeviceIDs []string
	SensorID  string
	Start     *time.Time
	End       *time.Time
	// LatestPerSensor returns only the newest point per sensor and device.
	LatestPerSensor bool
}

type seriesTable struct {
	SensorID  string
	TableName string
}

func (store *SensorSeriesStore) tables(ctx context.Context, sensorID string) ([]seriesTable, error) {
	var tables []seriesTable
	query := store.timeseries.WithContext(ctx).Table("sensor_series_tables").Select("sensor_id, table_name")
	if sensorID != "" {
		query = query.Where("sensor_id = ?", sensorID)
	}
	if err := query.Scan(&tables).Error; err != nil {
		return nil, err
	}

	return tables, nil
}

// Query reads points across the per-sensor tables, newest first.
func (store *SensorSeriesStore) Query(ctx context.Context, q SeriesQuery) ([]SeriesPoint, error) {
	tables, err := store.tables(ctx, q.SensorID)
	if err != nil {
		return nil, err
	}

	points := []SeriesPoint{}
	for _, table := range tables {
		db := store.timeseries.WithContext(ctx).Table(table.TableName).Select("device_id, value, time")
		if len(q.DeviceIDs) > 0 {
			db = db.Where("device_id IN ?", q.DeviceIDs)
		}
		if q.Start != nil {
			db = db.Where("time >= ?", *q.Start)
		}
		if q.End != nil {
			db = db.Where("time <= ?", *q.End)
		}

		var rows []struct {
			DeviceID string
			Value    float64
			Time     time.Time
		}
		if err := db.Order("time DESC").Scan(&rows).Error; err != nil {
			return nil, err
		}

		seen := map[string]bool{}
		for _, row := range rows {
			if q.LatestPerSensor {
				if seen[row.DeviceID] {
					continue
				}
				seen[row.DeviceID] = true
			}
			points = append(points, SeriesPoint{SensorID: table.SensorID, DeviceID: row.DeviceID, Value: row.Value, Time: row.Time})
		}
	}

	sort.SliceStable(points, func(i, j int) bool { return points[i].Time.After(points[j].Time) })
	return points, nil
}
